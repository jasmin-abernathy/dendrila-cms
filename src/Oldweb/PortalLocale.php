    public const LANGUAGES = ['fr' => 'Français', 'en' => 'English'];

    public static function selected(mixed $value): ?string
    {
        return is_string($value) && isset(self::LANGUAGES[$value]) ? $value : null;
    }

    public static function required(mixed $value): string
    {
        return self::selected($value) ?? throw new InvalidArgumentException('Choisis le français ou l’anglais.');
    }

    public static function text(string $language, string $message, string ...$arguments): string
    {
        $text = $language === 'en' ? (self::ENGLISH[$message] ?? $message) : $message;
        return $arguments === [] ? $text : sprintf($text, ...$arguments);
    }

    public static function escape(string $language): Closure
    {
        return static fn (string $message, string ...$arguments): string => htmlspecialchars(
            self::text($language, $message, ...$arguments), ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8'
        );
    }

