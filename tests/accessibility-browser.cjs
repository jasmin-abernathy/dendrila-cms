const assert=require('assert');
module.exports=async function accessibility(page){
 const opener=page.getByRole('button',{name:'Accessibilité',exact:true});
 await opener.focus();await page.keyboard.press('Enter');
 const dialog=page.getByRole('dialog',{name:'Confort de lecture'});
 await dialog.waitFor({state:'visible'});
 assert.equal(await page.locator(':focus').getAttribute('id'),'d-reading-close');
 await page.keyboard.press('Shift+Tab');
 assert(await page.locator(':focus').evaluate(el=>!!el.closest('dialog')),'Modal retains keyboard focus');
 await page.getByLabel('Taille du texte').selectOption('200');
 await page.getByLabel('Lecture simplifiée', {exact:false}).check();
 await page.getByLabel('Espacement du texte augmenté').check();
 await page.getByLabel('Réduire les animations').check();
 await page.getByLabel('Souligner les liens').check();
 assert.equal(await page.locator('html').getAttribute('data-reading-size'),'200');
 assert.equal(await page.locator('html').evaluate(el=>getComputedStyle(el).fontSize),'32px');
 const pair=await opener.evaluate(el=>[getComputedStyle(el).color,getComputedStyle(el).backgroundColor]);
 assert.deepEqual(pair,['rgb(255, 255, 255)','rgb(17, 17, 17)']);
 assert(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1),'Settings fit the screen with increased text');
 await page.keyboard.press('Escape');
 assert.equal(await page.locator(':focus').getAttribute('id'),'d-reading-open');
 await page.reload();
 await page.waitForFunction(()=>document.documentElement.dataset.readingSize==='200');
 assert.equal(await page.locator('html').getAttribute('data-reading-size'),'200','Preference survives reload');
 await opener.click();
 await page.getByRole('button',{name:'Réinitialiser les réglages'}).click();
 assert.equal(await page.locator('html').getAttribute('data-reading-size'),'100');
 assert.equal(await page.evaluate(()=>localStorage.getItem('dendrila.reading.v1')),null);
 await page.getByRole('button',{name:'Fermer',exact:true}).click();
};
